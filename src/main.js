function updateCurrentHeading() {
  const items = state.index?.outline || [];
  if (!items.length) return;

  let active = items[0];
  for (const item of items) {
    const target = document.getElementById(item.id);
    if (!target) continue;
    if (target.getBoundingClientRect().top <= window.innerHeight * 0.28) active = item;
    else break;
  }

  if (active.id !== state.activeOutlineId) {
    state.activeOutlineId = active.id;
    els.outlineNav.querySelectorAll('a[data-target]').forEach((link) => {
      link.setAttribute('aria-current', String(link.dataset.target === active.id));
    });
    els.currentSection.textContent = active.section;
    els.currentHeading.textContent = active.title;
  }
}

function updateReaderContext(id) {
  const target = document.getElementById(id);
  const items = state.index?.outline || [];
  if (!target || !items.length) return;

  let active = items[0];
  for (const item of items) {
    const heading = document.getElementById(item.id);
    if (!heading) continue;
    if (heading.getBoundingClientRect().top <= target.getBoundingClientRect().top + 1) active = item;
    else break;
  }

  state.activeOutlineId = active.id;
  els.currentSection.textContent = active.section;
  els.currentHeading.textContent = active.title;
  els.outlineNav.querySelectorAll('a[data-target]').forEach((link) => {
    link.setAttribute('aria-current', String(link.dataset.target === active.id));
  });
  expandSection(active.section);
}

function normalizeText(value) {
  return String(value || '').toLocaleLowerCase('zh-CN');
}

function renderInlineMath(root) {
  const replacements = [
    [/\\beta\b/g, 'β'], [/\\alpha\b/g, 'α'], [/\\gamma\b/g, 'γ'],
    [/\\delta\b/g, 'δ'], [/\\theta\b/g, 'θ'], [/\\mu\b/g, 'μ'],
    [/\\geq\b/g, '≥'], [/\\leq\b/g, '≤'], [/\\times\b/g, '×'],
    [/\\uparrow\b/g, '↑'], [/\\downarrow\b/g, '↓'],
    [/\\%/g, '%'], [/\\,/g, ' '], [/\\!/g, ''],
  ];
  root.querySelectorAll('math').forEach((node) => {
    let value = node.textContent || '';
    for (const [pattern, replacement] of replacements) value = value.replace(pattern, replacement);
    value = value.replace(/\\text\{([^{}]*)\}/g, '$1');
    value = value.replace(/([A-Za-z][A-Za-z0-9]*)_\{?([A-Za-z0-9+-]+)\}?/g, '$1<sub>$2</sub>');
    value = value.replace(/([A-Za-z0-9]+)\^\{?([A-Za-z0-9+-]+)\}?/g, '$1<sup>$2</sup>');
    node.classList.add('math-inline');
    node.innerHTML = value;
  });
}

function escapeHTML(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

function escapeAttr(value) {
  return escapeHTML(value);
}

function isEditable(element) {
  return element instanceof HTMLElement && (
    element.tagName === 'INPUT' ||
    element.tagName === 'TEXTAREA' ||
    element.tagName === 'SELECT' ||
    element.isContentEditable
  );
}
